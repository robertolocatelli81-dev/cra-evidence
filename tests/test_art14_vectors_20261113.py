"""13/11/2026 — spec/art14-filing/v0.1/vectors (spec §6): the verifier gives the expected verdict and reason code on
every vector, through the library and through `cra verify-attestation` (exit 0 / 1); the vectors are what
scripts/gen_art14_vectors.py produces (regenerated byte for byte); the keys are the labelled test-only keys; every rule
family of §2-§5 has a vector. Signature checks need `cryptography`: skipped without it, except the check that a host
without it never says "verified"."""
import builtins, contextlib, hashlib, importlib.util, io, json, os, shutil, sys, tempfile, unittest
from unittest import mock

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
V = os.path.join(ROOT, "spec", "art14-filing", "v0.1", "vectors")
HAVE_CRYPTO = importlib.util.find_spec("cryptography") is not None
sys.path.insert(0, os.path.join(ROOT, "scripts"))



def check_published_vectors(test, root, subdir):
    """every published vector file of `subdir` keeps the sha256 it was published with
    (tests/fixtures/art14_vectors_published_sha256.txt): a release must not change them"""
    import hashlib
    pins = {}
    with open(os.path.join(root, "tests", "fixtures", "art14_vectors_published_sha256.txt"), encoding="utf-8") as f:
        for line in f:
            h, p = line.rstrip("\n").split("  ", 1)
            if p.startswith(subdir + "/"):
                pins[p] = h
    test.assertTrue(pins, subdir)
    for p, h in sorted(pins.items()):
        with open(os.path.join(root, p), "rb") as f:
            test.assertEqual(hashlib.sha256(f.read()).hexdigest(), h, p)


def manifest():
    with open(os.path.join(V, "manifest.json"), encoding="utf-8") as f:
        return json.load(f)


def run(v):
    from cra_evidence.art14_attest import verify_envelope
    from cra_evidence.ledger import load_trust_store
    with open(os.path.join(V, v["trust_store"]), encoding="utf-8") as f:
        ts = load_trust_store(f.read())
    return verify_envelope(os.path.join(V, v["envelope"]), ts, v["drop"] and os.path.join(V, v["drop"]),
                           v["ledger"] and os.path.join(V, v["ledger"]))


def cli(*argv):
    from cra_evidence.cli import main
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            rc = main(list(argv))
        except SystemExit as e:
            rc = e.code
    return rc, out.getvalue(), err.getvalue()


@unittest.skipUnless(HAVE_CRYPTO, "the vectors are signed: cryptography needed to check them")
class TestVectors(unittest.TestCase):
    def test_every_vector_gives_its_expected_verdict(self):
        m = manifest()
        self.assertGreaterEqual(len(m["vectors"]), 40)
        for v in m["vectors"]:
            with self.subTest(vector=v["name"]):
                r = run(v)
                codes = [x["code"] for x in r["reasons"]]
                self.assertEqual(r["verified"], v["expect"]["verified"], codes)
                self.assertEqual(sorted(set(codes)), sorted(set(v["expect"]["codes"])), codes)   # exactly the expected codes
                if r["verified"]:
                    self.assertEqual(codes, [])
                    self.assertTrue(r["trusted"])
                    self.assertEqual(r["statement"], "accepted")
                else:
                    self.assertTrue(codes)
                for k in ("drop", "ledger", "product"):
                    if k in v["expect"]:
                        self.assertEqual(r[k], v["expect"][k])
                    obj = v["ledger"] if k == "product" else v[k]
                    if obj is None:
                        self.assertTrue(r[k].startswith("not_evaluated"))   # never PASS without the object (§4.2 rule 3)
                    elif r["verified"]:
                        self.assertEqual(r[k], "PASS")
                for k in ("statement_unrecognized", "envelope_unrecognized"):
                    self.assertEqual(r[k], v["expect"].get(k, []))
                if r["verified"]:
                    self.assertEqual([x["code"] for x in r["signatures_not_verified"]], v["expect"].get("listed", []))

    def test_cli_exit_codes(self):
        for v in manifest()["vectors"]:
            argv = ["verify-attestation", os.path.join(V, v["envelope"]), "--trust-store", os.path.join(V, v["trust_store"])]
            if v["drop"]:
                argv += ["--drop", os.path.join(V, v["drop"])]
            if v["ledger"]:
                argv += ["--ledger", os.path.join(V, v["ledger"])]
            with self.subTest(vector=v["name"]):
                rc, out, err = cli(*argv)
                self.assertEqual(rc, v["expect"]["exit"], out[-500:])
                self.assertEqual(json.loads(out)["verified"], v["expect"]["verified"])

    def test_vectors_are_the_generator_output(self):
        import gen_art14_vectors
        d = tempfile.mkdtemp()
        try:
            out = os.path.join(d, "vectors")
            m = gen_art14_vectors.generate(out)
            self.assertEqual(len(m["vectors"]), len(manifest()["vectors"]))   # the script prints it
            check_published_vectors(self, ROOT, "spec/art14-filing/v0.1/vectors")
            mine, theirs = sorted(os.listdir(out)), sorted(os.listdir(V))
            self.assertEqual(mine, theirs)
            for n in mine:
                with open(os.path.join(out, n), "rb") as a, open(os.path.join(V, n), "rb") as b:
                    self.assertEqual(a.read(), b.read(), n)
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def test_keys_are_the_labelled_test_keys(self):
        from cryptography.hazmat.primitives import serialization as ser
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
        m = manifest()
        self.assertIn("TEST-ONLY", m["test_keys"]["warning"])
        for kid in ("test-signer", "not-in-trust-store"):
            k = m["test_keys"][kid]
            self.assertIn("TEST-ONLY", k["seed_string"])
            sk = Ed25519PrivateKey.from_private_bytes(hashlib.sha256(k["seed_string"].encode()).digest())
            self.assertEqual(sk.public_key().public_bytes(ser.Encoding.Raw, ser.PublicFormat.Raw).hex(), k["public_key_hex"])
        with open(os.path.join(V, "trust_store.json"), encoding="utf-8") as f:
            self.assertEqual(json.load(f), {"test-signer": m["test_keys"]["test-signer"]["public_key_hex"]})

    def test_every_rule_family_has_a_vector(self):
        codes = {c for v in manifest()["vectors"] for c in v["expect"]["codes"]}
        self.assertEqual(codes, {"payload_type", "base64", "not_trusted", "signature_failed", "unknown_keyid", "weak_key",
                                 "envelope_malformed", "statement_type", "predicate_type", "subject", "subject_digest",
                                 "predicate_unknown_key", "predicate_missing_key", "predicate_type_error", "duplicate_key",
                                 "predicate_enum", "predicate_timestamp", "predicate_rule", "deadline", "rule1", "rule2",
                                 "rule3", "rule4", "drop_mismatch", "product"})
        self.assertEqual(sum(1 for v in manifest()["vectors"] if v["expect"]["verified"]), 10)


class TestWithoutCryptography(unittest.TestCase):
    def test_a_host_without_cryptography_never_says_verified(self):
        real = builtins.__import__

        def no_crypto(name, *a, **k):
            if name.startswith("cryptography"):
                raise ImportError("no cryptography (simulated)")
            return real(name, *a, **k)
        v = next(x for x in manifest()["vectors"] if x["name"] == "valid_early_warning")
        with mock.patch.object(builtins, "__import__", no_crypto):
            r = run(v)
        self.assertFalse(r["verified"]); self.assertFalse(r["trusted"]); self.assertFalse(r["assessed"])
        self.assertEqual([x["code"] for x in r["reasons"]], ["not_checkable"])
        self.assertEqual(r["statement"], "not_evaluated")


if __name__ == "__main__":
    unittest.main()
