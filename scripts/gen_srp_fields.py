"""The tables of spec/SRP_FIELDS.md, generated from cra_evidence/srp_notice.py (the module is the single source of the
tables; tests/test_srp_glossary_16.py checks that the document carries exactly this text between its two markers).
  python scripts/gen_srp_fields.py           print the tables
  python scripts/gen_srp_fields.py --write   rewrite them in spec/SRP_FIELDS.md"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from cra_evidence.srp_notice import CURRENT_GLOSSARY, GLOSSARIES  # noqa: E402

BEGIN = "<!-- tables: generated by scripts/gen_srp_fields.py from cra_evidence/srp_notice.py; tests/test_srp_glossary_16.py checks them -->"
END = "<!-- end of tables -->"
TITLES = {"Both": "Common fields", "AEV": "Actively exploited vulnerability", "SI": "Severe incident"}


def _fmt(spec):
    f = spec["format"]
    if f in ("enum", "enum-list"):
        out = f"{f} {spec['enum']}"
    elif f == "text":
        out = f"text (max {spec['max']})" if spec.get("max") else "text (no maximum in the glossary)"
    else:
        out = f
    notes = []
    for stage, need in sorted(spec.get("when", {}).items()):
        notes.append(f"{stage}: only with `{need}`")
    if spec.get("entered_by"):
        notes.append(f"entered by the {spec['entered_by']}: refused in a notice")
    return out + (f" — {'; '.join(notes)}" if notes else "")


def _table(fields):
    out = ["| row | field | EW 24h | N 72h | FR | format |", "|---|---|---|---|---|---|"]
    for k, s in fields.items():
        st = s["stages"]
        out.append(f"| {s['glossary_row']} | `{k}` | {st['early_warning']} | {st['notification']} | {st['final_report']} | {_fmt(s)} |")
    return "\n".join(out)


def tables() -> str:
    parts = []
    for v in (CURRENT_GLOSSARY, "enisa_srp_glossary_20260929"):
        g = GLOSSARIES[v]
        parts.append(f"## Tables of `{v}` ({g['page']}; rules {g['rules']})")
        for scope, t in g["groups"]:
            parts.append(f"### {TITLES[scope]} ({len(t)})\n\n{_table(t)}")
    parts.append("`enisa_srp_glossary_20260915` is `enisa_srp_glossary_20260929` without row v26a "
                 "(`vulnerability_occurred_datetime_utc`).")
    return "\n\n".join(parts)


def render(doc: str) -> str:
    a, b = doc.index(BEGIN) + len(BEGIN), doc.index(END)
    return doc[:a] + "\n\n" + tables() + "\n\n" + doc[b:]


if __name__ == "__main__":
    p = os.path.join(ROOT, "spec", "SRP_FIELDS.md")
    with open(p, encoding="utf-8") as f:
        doc = f.read()
    if "--write" in sys.argv[1:]:
        with open(p, "w", encoding="utf-8") as f:
            f.write(render(doc))
    else:
        sys.stdout.write(tables() + "\n")
